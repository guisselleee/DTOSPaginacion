CREATE TABLE IF NOT EXISTS weill_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    external_user_id VARCHAR(120) UNIQUE,
    email VARCHAR(254) UNIQUE,
    role VARCHAR(16) NOT NULL DEFAULT 'USER',
    password_hash VARCHAR(100),
    display_name VARCHAR(160) NOT NULL,
    education_level VARCHAR(120),
    school_center VARCHAR(180),
    municipality VARCHAR(120),
    department VARCHAR(120),
    birth_date DATE,
    currently_studying BOOLEAN,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_weill_users_role
        CHECK (role IN ('ADMIN', 'USER')),
    CONSTRAINT ck_weill_admin_password
        CHECK (role <> 'ADMIN' OR password_hash IS NOT NULL)
);

