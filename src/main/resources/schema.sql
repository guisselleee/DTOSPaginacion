CREATE UNIQUE INDEX IF NOT EXISTS uq_weill_users_email
    ON weill_users(LOWER(email))
    WHERE email IS NOT NULL;

CREATE TABLE IF NOT EXISTS weill_test_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES weill_users(id),
    status VARCHAR(24) NOT NULL DEFAULT 'IN_PROGRESS',
    started_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    total_score INTEGER NOT NULL DEFAULT 0,
    max_score INTEGER NOT NULL DEFAULT 60,
    CONSTRAINT ck_weill_attempt_status
        CHECK (status IN ('IN_PROGRESS', 'COMPLETED', 'ABANDONED')),
    CONSTRAINT ck_weill_attempt_total_score
        CHECK (total_score BETWEEN 0 AND max_score),
    CONSTRAINT ck_weill_attempt_max_score
        CHECK (max_score = 60)
);

CREATE TABLE IF NOT EXISTS weill_item_responses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id BIGINT NOT NULL REFERENCES weill_test_attempts(id) ON DELETE CASCADE,
    page_number SMALLINT NOT NULL,
    row_number SMALLINT NOT NULL,
    item_number SMALLINT NOT NULL,
    selected_option SMALLINT NOT NULL,
    correct_option SMALLINT NOT NULL,
    is_correct BOOLEAN NOT NULL DEFAULT FALSE,
    score SMALLINT NOT NULL DEFAULT 0,
    answered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_weill_response_item
        UNIQUE (attempt_id, page_number, row_number, item_number),
    CONSTRAINT ck_weill_response_page
        CHECK (page_number BETWEEN 1 AND 5),
    CONSTRAINT ck_weill_response_row
        CHECK (row_number BETWEEN 1 AND 4),
    CONSTRAINT ck_weill_response_item
        CHECK (item_number BETWEEN 1 AND 3),
    CONSTRAINT ck_weill_response_selected_option
        CHECK (selected_option BETWEEN 1 AND 8),
    CONSTRAINT ck_weill_response_correct_option
        CHECK (correct_option BETWEEN 1 AND 8),
    CONSTRAINT ck_weill_response_score
        CHECK (score IN (0, 1)),
    CONSTRAINT ck_weill_response_correct_score
        CHECK (
            (is_correct = TRUE AND score = 1)
            OR (is_correct = FALSE AND score = 0)
        )
);

CREATE INDEX IF NOT EXISTS idx_weill_attempts_user_id
    ON weill_test_attempts(user_id);

CREATE INDEX IF NOT EXISTS idx_weill_attempts_status
    ON weill_test_attempts(status);

CREATE INDEX IF NOT EXISTS idx_weill_responses_attempt_id
    ON weill_item_responses(attempt_id);
